var update = flag.Bool("update", false, "rewrite golden files")

const testInstance = "0123456789abcdef0123456789abcdef"

func golden(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", "golden", name)
	if *update {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run go test ./internal/build -run Dockerfile -update)", err)
	}
	if string(want) != string(got) {
		t.Fatalf("%s differs from the golden file:\n%s", name, got)
	}
}

// instructions are the Dockerfile instructions the generator may emit;
// every line must start with one (or be a comment or blank), so no value
// can smuggle in a line of its own.
var instructions = []string{"FROM ", "COPY ", "RUN ", "ENV ", "WORKDIR ", "USER ", "EXPOSE ", "ENTRYPOINT "}

func checkLines(t *testing.T, df []byte) {
	t.Helper()
	for _, l := range strings.Split(strings.TrimSuffix(string(df), "\n"), "\n") {
		if l == "" || strings.HasPrefix(l, "# Generated by golem-deploy") {
			continue
		}
		ok := false
		for _, in := range instructions {
			ok = ok || strings.HasPrefix(l, in)
		}
		if !ok || strings.HasSuffix(l, `\`) {
			t.Fatalf("unexpected line %q", l)
		}
	}
}

func TestDockerfileGolden(t *testing.T) {
	fixture, err := Inspect(filepath.Join("testdata", "game"), false)
	if err != nil {
		t.Fatal(err)
	}
	cases := map[string]struct {
		plan *Plan
		prm  DockerfileParams
	}{
		"fixture.Dockerfile": {fixture, DockerfileParams{ProjectID: 7, InstanceID: testInstance, Addons: true}},
		"subdir.Dockerfile": {&Plan{
			Root: "games/arena", EngineVersion: "v0.4.2", GoVersion: "1.26.2", ServerPackage: "cmd/arena",
			ServerArgs: []string{"-assets", "client/dist", `--motd=it's "quoted" $HOME \n`, "]", `"],["sh","-c","evil"]`},
			Bake:       BakeCheck,
			NPM:        []NPMDir{{Dir: ".", Lockfile: true}, {Dir: "client", Lockfile: false}},
			WebDir:     "client", WebBuild: []string{"npm", "run", "build:prod", "--", "--base=/game/"}, WebDist: "client/dist",
		}, DockerfileParams{ProjectID: 12, InstanceID: testInstance}},
		"go-only.Dockerfile": {&Plan{
			Root: ".", EngineVersion: "v0.4.0-rc.1", GoVersion: "1.25", ServerPackage: ".", Bake: BakeGenerate,
		}, DockerfileParams{ProjectID: 1, InstanceID: testInstance}},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			df, err := Dockerfile(tc.plan, tc.prm)
			if err != nil {
				t.Fatal(err)
			}
			checkLines(t, df)
			golden(t, name, df)
		})
	}
}

// TestDockerfileRejectsUnsafePlans pins that the generator re-validates
// every value even if a plan did not come from Inspect.
func TestDockerfileRejectsUnsafePlans(t *testing.T) {
	ok := func() *Plan {
		return &Plan{Root: ".", EngineVersion: "v0.4.0", GoVersion: "1.25.4", ServerPackage: "cmd/server",
			NPM: []NPMDir{{Dir: "."}}, WebDir: ".", WebBuild: []string{"npm", "run", "build"}, WebDist: "web/dist"}
	}
	prm := DockerfileParams{ProjectID: 1, InstanceID: testInstance}
	if _, err := Dockerfile(ok(), prm); err != nil {
		t.Fatal(err)
	}
	bad := map[string]func(*Plan){
		"root traversal":          func(p *Plan) { p.Root = "../x" },
		"root with newline":       func(p *Plan) { p.Root = "a\nRUN evil" },
		"package with space":      func(p *Plan) { p.ServerPackage = "cmd/a b" },
		"package option":          func(p *Plan) { p.ServerPackage = "-toolexec=evil" },
		"dist with dollar":        func(p *Plan) { p.WebDist = "$X" },
		"dist root":               func(p *Plan) { p.WebDist = "." },
		"web dir absolute":        func(p *Plan) { p.WebDir = "/etc" },
		"npm dir quote":           func(p *Plan) { p.NPM = []NPMDir{{Dir: `a"b`}} },
		"engine version injected": func(p *Plan) { p.EngineVersion = "v0.4.0 --check\nRUN evil" },
		"engine version bare":     func(p *Plan) { p.EngineVersion = "latest" },
		"go version injected":     func(p *Plan) { p.GoVersion = "1.25-bookworm AS x\nFROM evil" },
		"arg newline":             func(p *Plan) { p.ServerArgs = []string{"a\nRUN evil"} },
		"build word cr":           func(p *Plan) { p.WebBuild = []string{"npm", "a\rb"} },
		"build empty":             func(p *Plan) { p.WebBuild = []string{""} },
	}
	for name, mutate := range bad {
		t.Run(name, func(t *testing.T) {
			p := ok()
			mutate(p)
			if df, err := Dockerfile(p, prm); err == nil {
				t.Fatalf("accepted:\n%s", df)
			}
		})
	}
	if _, err := Dockerfile(ok(), DockerfileParams{ProjectID: 1, InstanceID: "zz"}); err == nil {
		t.Fatal("bad instance id accepted")
	}
	if _, err := Dockerfile(&Plan{Custom: true}, prm); err == nil {
		t.Fatal("custom plan rendered")
	}
}

func TestCacheIDsArePerProject(t *testing.T) {
	a, _ := Dockerfile(&Plan{Root: ".", EngineVersion: "v0.4.0", GoVersion: "1.25.4", ServerPackage: "."}, DockerfileParams{ProjectID: 1, InstanceID: testInstance})
	b, _ := Dockerfile(&Plan{Root: ".", EngineVersion: "v0.4.0", GoVersion: "1.25.4", ServerPackage: "."}, DockerfileParams{ProjectID: 2, InstanceID: testInstance})
	c, _ := Dockerfile(&Plan{Root: ".", EngineVersion: "v0.4.0", GoVersion: "1.25.4", ServerPackage: "."}, DockerfileParams{ProjectID: 1, InstanceID: "fedcba9876543210fedcba9876543210"})
	for _, df := range [][]byte{a, b, c} {
		if strings.Count(string(df), "id=golem-deploy-") != 4 {
			t.Fatalf("cache mounts:\n%s", df)
		}
	}
	ida := cacheID(DockerfileParams{ProjectID: 1, InstanceID: testInstance}, "gomod")
	idb := cacheID(DockerfileParams{ProjectID: 2, InstanceID: testInstance}, "gomod")
	idc := cacheID(DockerfileParams{ProjectID: 1, InstanceID: "fedcba9876543210fedcba9876543210"}, "gomod")
	if ida == idb || ida == idc || !strings.HasSuffix(ida, "-p1-gomod") || !strings.HasSuffix(idb, "-p2-gomod") ||
		!strings.Contains(string(a), "id="+ida+",") || !strings.Contains(string(b), "id="+idb+",") || !strings.Contains(string(c), "id="+idc+",") {
		t.Fatalf("cache ids not scoped: %s %s %s", ida, idb, idc)
	}
	// The instance id itself never appears (the Dockerfile is shown in build
	// logs, which developers read).
	for _, df := range [][]byte{a, b} {
		if strings.Contains(string(df), testInstance[:8]) {
			t.Fatalf("instance id in the Dockerfile:\n%s", df)
		}
	}
}

func TestDockerignore(t *testing.T) {
	got := string(Dockerignore([]byte("!.git\n*.log")))
	want := "!.git\n*.log\n# Always excluded by golem-deploy:\n.git\n**/.git\nnode_modules\n**/node_modules\n"
	if got != want {
		t.Fatalf("%q", got)
	}
	if !strings.HasPrefix(string(Dockerignore(nil)), "# Always excluded") {
		t.Fatal("empty repo ignore")
	}
}
