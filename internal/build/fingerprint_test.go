package build

import (
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

const testFingerprint = "a1b2c3d4e5f60718293a4b5c6d7e8f90a1b2c3d4e5f60718293a4b5c6d7e8f90"

func helpersGo(fp string) string {
	return "// Code generated by golem-bake. DO NOT EDIT.\n\npackage generated\n\n// SchemaFingerprint identifies the schema.\nconst SchemaFingerprint = \"" + fp + "\"\n"
}

// The fingerprint is read from the committed generated code when the build
// verifies it (golem-bake --check) and is unknown otherwise; nothing about
// it can fail a build.
func TestCommittedFingerprint(t *testing.T) {
	files := baseRepo()
	files["internal/generated/golem_helpers.go"] = helpersGo(testFingerprint)
	p, err := Inspect(writeRepo(t, files), false)
	if err != nil {
		t.Fatal(err)
	}
	if p.Bake != BakeCheck || p.SchemaFingerprint != testFingerprint {
		t.Fatalf("bake %v fingerprint %q", p.Bake, p.SchemaFingerprint)
	}
	// In a game root below the repository root.
	sub := map[string]string{"golem-deploy.yaml": "root: games/arena\n"}
	for k, v := range files {
		sub["games/arena/"+k] = v
	}
	if p, err := Inspect(writeRepo(t, sub), false); err != nil || p.SchemaFingerprint != testFingerprint {
		t.Fatalf("%+v %v", p, err)
	}
	cases := map[string]func(map[string]string){
		"generated code not committed": func(f map[string]string) {
			delete(f, "internal/generated/golem_helpers.go")
			delete(f, "internal/game/a.go")
		},
		"no declaration": func(f map[string]string) {
			f["internal/generated/golem_helpers.go"] = "package generated\n"
		},
		"two declarations": func(f map[string]string) {
			f["internal/generated/golem_helpers.go"] = helpersGo(testFingerprint) + helpersGo(strings.Repeat("0", 64))
		},
		"commented out": func(f map[string]string) {
			f["internal/generated/golem_helpers.go"] = "package generated\n// const SchemaFingerprint = \"" + testFingerprint + "\"\n"
		},
		"not hex": func(f map[string]string) {
			f["internal/generated/golem_helpers.go"] = helpersGo(strings.Repeat("Z", 64))
		},
		"too large": func(f map[string]string) {
			f["internal/generated/golem_helpers.go"] = helpersGo(testFingerprint) + strings.Repeat("// x\n", maxHelpersBytes/5+1)
		},
		"no go-server integration": func(f map[string]string) {
			f["golem.yaml"] = "proto:\n  out: internal/generated/entities.proto\n"
			f["internal/generated/entities.proto"] = "x"
		},
		"output outside the game": func(f map[string]string) {
			f["golem.yaml"] = "integrations:\n  go-server:\n    out: ../elsewhere/\n  js:\n    out: internal/generated/\n"
		},
		"custom Dockerfile": func(f map[string]string) {
			f["golem-deploy.yaml"] = "dockerfile: Dockerfile\n"
			f["Dockerfile"] = "FROM scratch\n"
		},
	}
	for name, mut := range cases {
		f := baseRepo()
		f["internal/generated/golem_helpers.go"] = helpersGo(testFingerprint)
		mut(f)
		p, err := Inspect(writeRepo(t, f), true)
		if err != nil {
			t.Errorf("%s: %v", name, err)
			continue
		}
		if p.SchemaFingerprint != "" {
			t.Errorf("%s: fingerprint %q", name, p.SchemaFingerprint)
		}
	}
}

func TestCommittedFingerprintSymlink(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("symbolic links need privileges on Windows")
	}
	f := baseRepo()
	f["outside/golem_helpers.go"] = helpersGo(testFingerprint)
	delete(f, "internal/game/a.go")
	f["internal/generated/other.go"] = "package generated\n"
	dir := writeRepo(t, f)
	if err := os.Symlink(filepath.Join(dir, "outside", "golem_helpers.go"), filepath.Join(dir, "internal", "generated", "golem_helpers.go")); err != nil {
		t.Fatal(err)
	}
	p, err := Inspect(dir, false)
	if err != nil || p.SchemaFingerprint != "" {
		t.Fatalf("%+v %v", p, err)
	}
}
