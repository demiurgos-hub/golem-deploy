package build

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"regexp"
	"strconv"
	"strings"
)

// Images of the generated Dockerfile. The Go image's tag comes from the
// game's go.mod (golang:<version>-bookworm).
const (
	NodeImage    = "node:24-bookworm-slim"
	RuntimeImage = "gcr.io/distroless/static-debian12:nonroot"
	// ServerBinary is where the game server binary is installed in the
	// image; the image's working directory is AppDir (the game root).
	ServerBinary = "/usr/local/bin/golem-server"
	AppDir       = "/app"
	// DataDir is created in the image, owned by RuntimeUID.
	DataDir    = "/data"
	RuntimeUID = 65532
	// StaticContext is the name of the build context holding the static
	// add-ons (--build-context static=<dir>).
	StaticContext = "static"
	// GamePort is the port the server listens on (UDP and TCP).
	GamePort = 7777
)

// MandatoryIgnores are appended to every build's .dockerignore (after the
// repository's own patterns, so they win): Git metadata never enters the
// build context, nor do installed dependencies.
var MandatoryIgnores = []string{".git", "**/.git", "node_modules", "**/node_modules"}

// DockerfileParams are the daemon-side inputs of the generated Dockerfile.
type DockerfileParams struct {
	ProjectID  int64
	InstanceID string
	// Addons adds the static add-on COPY instructions.
	Addons bool
}

var hexRE = regexp.MustCompile(`^[0-9a-f]{12,64}$`)

// cacheID scopes a BuildKit cache mount to one project of one
// installation, so one project cannot read or poison another's caches.
// The installation part is a hash of the instance id (the generated
// Dockerfile appears in build logs; the instance id itself is never shown).
func cacheID(prm DockerfileParams, what string) string {
	sum := sha256.Sum256([]byte("golem-deploy build cache\x00" + prm.InstanceID))
	return "golem-deploy-" + hex.EncodeToString(sum[:6]) + "-p" + strconv.FormatInt(prm.ProjectID, 10) + "-" + what
}

// Dockerfile renders the generated multi-stage Dockerfile for p. Every
// value placed in it is either a constant, a number, a version matched by a
// strict pattern, a path that passed cleanPath, or a list of words rendered
// as one JSON array (exec form: no shell, no variable expansion, always a
// single line).
func Dockerfile(p *Plan, prm DockerfileParams) ([]byte, error) {
	if p.Custom {
		return nil, fmt.Errorf("build: plan uses a custom Dockerfile")
	}
	if prm.ProjectID <= 0 || !hexRE.MatchString(prm.InstanceID) {
		return nil, fmt.Errorf("build: invalid project or instance id")
	}
	if !goVersionRE.MatchString(p.GoVersion) || !ValidEngineVersion(p.EngineVersion) {
		return nil, fmt.Errorf("build: invalid version in plan")
	}
	for _, v := range append([]string{p.Root, p.ServerPackage, p.WebDir}, npmDirs(p)...) {
		if _, err := cleanPath("plan", v, true); err != nil {
			return nil, fmt.Errorf("build: invalid path in plan")
		}
	}
	if p.WebDist != "" {
		if _, err := cleanPath("plan", p.WebDist, false); err != nil {
			return nil, fmt.Errorf("build: invalid path in plan")
		}
	}
	if err := checkWords("server.args", p.ServerArgs, false); err != nil {
		return nil, err
	}
	if p.WebBuild != nil {
		if err := checkWords("web.build", p.WebBuild, true); err != nil {
			return nil, err
		}
	}

	src := join("/src", p.Root)
	npmCache := "--mount=type=cache,id=" + cacheID(prm, "npm") + ",target=/root/.npm"
	goCache := "--mount=type=cache,id=" + cacheID(prm, "gomod") + ",target=/go/pkg/mod " +
		"--mount=type=cache,id=" + cacheID(prm, "gobuild") + ",target=/root/.cache/go-build"

	var b strings.Builder
	line := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	line("# Generated by golem-deploy for project %d. It is not part of the repository.", prm.ProjectID)
	line("FROM golang:%s-bookworm AS build", p.GoVersion)
	if len(p.NPM) > 0 {
		line("COPY --from=%s /usr/local/bin/node /usr/local/bin/node", NodeImage)
		line("COPY --from=%s /usr/local/lib/node_modules/npm /usr/local/lib/node_modules/npm", NodeImage)
		line("RUN %s", execForm("ln", "-s", "/usr/local/lib/node_modules/npm/bin/npm-cli.js", "/usr/local/bin/npm"))
		line("RUN %s", execForm("ln", "-s", "/usr/local/lib/node_modules/npm/bin/npx-cli.js", "/usr/local/bin/npx"))
	}
	line("ENV CGO_ENABLED=0 GOWORK=off GOFLAGS=-mod=mod NPM_CONFIG_UPDATE_NOTIFIER=false NPM_CONFIG_FUND=false NPM_CONFIG_AUDIT=false")
	if len(p.NPM) > 0 {
		// Locally installed tools (tsc for golem-bake, the web build's own
		// tools) come after the system directories.
		var bins []string
		for _, d := range p.NPM {
			bins = append(bins, join(src, d.Dir, "node_modules/.bin"))
		}
		line("ENV PATH=$PATH:%s", strings.Join(bins, ":"))
	}
	wd := ""
	workdir := func(d string) {
		if d != wd {
			line("WORKDIR %s", d)
			wd = d
		}
	}
	workdir("/src")
	line("COPY . .")
	if prm.Addons {
		line("COPY --from=%s / %s/", StaticContext, strings.TrimSuffix(src, "/"))
	}
	for _, d := range p.NPM {
		workdir(join(src, d.Dir))
		if d.Lockfile {
			line("RUN %s %s", npmCache, execForm("npm", "ci"))
		} else {
			line("RUN %s %s", npmCache, execForm("npm", "install"))
		}
	}
	workdir(src)
	bake := []string{"go", "run", EngineModule + "/cmd/golem-bake@" + p.EngineVersion}
	if p.Bake == BakeCheck {
		bake = append(bake, "--check")
	}
	line("RUN %s %s", goCache, execForm(bake...))
	if p.WebBuild != nil {
		workdir(join(src, p.WebDir))
		line("RUN %s %s", npmCache, execForm(p.WebBuild...))
	}
	workdir(src)
	if p.WebDist != "" {
		// The path passed cleanPath: no quoting or expansion is possible.
		line(`RUN test -d %s || { echo "golem-deploy: the web client directory %s (web.dist) does not exist after the web build" >&2; exit 1; }`, p.WebDist, p.WebDist)
	}
	pkg := "."
	if p.ServerPackage != "." {
		pkg = "./" + p.ServerPackage
	}
	line("RUN %s %s", goCache, execForm("go", "build", "-trimpath", "-ldflags=-s -w", "-o", "/out/golem-server", pkg))
	line("RUN %s", execForm("mkdir", "-p", "/out/data"))
	line("")
	line("FROM %s", RuntimeImage)
	wd = ""
	workdir(AppDir)
	line("COPY --from=build /out/golem-server %s", ServerBinary)
	if p.WebDist != "" {
		line("COPY --from=build %s %s", join(src, p.WebDist), join(AppDir, p.WebDist))
	}
	if prm.Addons {
		line("COPY --from=%s / %s/", StaticContext, AppDir)
	}
	line("COPY --from=build --chown=%d:%d /out/data %s", RuntimeUID, RuntimeUID, DataDir)
	line("USER %d:%d", RuntimeUID, RuntimeUID)
	line("EXPOSE %d/udp %d/tcp", GamePort, GamePort)
	line("ENTRYPOINT %s", execForm(append([]string{ServerBinary}, p.ServerArgs...)...))
	return []byte(b.String()), nil
}

func npmDirs(p *Plan) []string {
	var out []string
	for _, d := range p.NPM {
		out = append(out, d.Dir)
	}
	return out
}

// execForm renders words as a Dockerfile JSON array on one line (HTML
// characters are not escaped; control characters cannot occur, see
// checkWords, and would be escaped by the encoder anyway).
func execForm(words ...string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if words == nil {
		words = []string{}
	}
	_ = enc.Encode(words)
	return strings.TrimSuffix(buf.String(), "\n")
}

// Dockerignore returns the .dockerignore of a build: the repository's own
// patterns followed by MandatoryIgnores.
func Dockerignore(repo []byte) []byte {
	var b bytes.Buffer
	if len(repo) > 0 {
		b.Write(repo)
		if !bytes.HasSuffix(repo, []byte("\n")) {
			b.WriteByte('\n')
		}
	}
	b.WriteString("# Always excluded by golem-deploy:\n")
	for _, p := range MandatoryIgnores {
		b.WriteString(p + "\n")
	}
	return b.Bytes()
}
